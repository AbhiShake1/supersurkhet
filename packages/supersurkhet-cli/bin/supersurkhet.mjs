#!/usr/bin/env node

import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const args = process.argv.slice(2);
const command = args[0];

const SCHEMA_DATA_TYPES = new Set([
  'string',
  'number',
  'boolean',
  'date',
  'enum',
  'array',
  'object',
]);

function ensureDir(path) {
  mkdirSync(path, { recursive: true });
}

function writeText(path, content) {
  ensureDir(dirname(path));
  writeFileSync(path, content, 'utf8');
}

function parseFlag(name, fallback) {
  const index = args.indexOf(name);
  if (index === -1) return fallback;
  return args[index + 1] ?? fallback;
}

function inferType(field) {
  const dataType = field.dataType ?? field.type;
  if (!SCHEMA_DATA_TYPES.has(dataType)) {
    return 'unknown';
  }

  if (dataType === 'string' || dataType === 'date') return 'string';
  if (dataType === 'number') return 'number';
  if (dataType === 'boolean') return 'boolean';
  if (dataType === 'enum') {
    return Array.isArray(field.enumValues) && field.enumValues.length > 0
      ? field.enumValues.map((v) => JSON.stringify(v)).join(' | ')
      : 'string';
  }
  if (dataType === 'array') {
    const item = field.itemType ? inferType({ ...field.itemType, key: 'item' }) : 'unknown';
    return `${item}[]`;
  }
  if (dataType === 'object') {
    const entries = Array.isArray(field.fields)
      ? field.fields
          .map((child) => `${child.key}${child.optional ? '?' : ''}: ${inferType(child)};`)
          .join(' ')
      : '';
    return `{ ${entries} }`;
  }
  return 'unknown';
}

function generateTypes(schemaDocs, rootTypeName = 'SupersurkhetSchemaMap') {
  const out = [
    '// Auto-generated by supersurkhet CLI. Do not edit manually.',
    `export type ${rootTypeName} = {`,
  ];

  for (const schema of schemaDocs) {
    out.push(`  ${JSON.stringify(schema.schemaId)}: {`);
    for (const field of schema.fields ?? []) {
      out.push(`    ${field.key}${field.optional ? '?' : ''}: ${inferType(field)};`);
    }
    out.push('  };');
  }

  out.push('};');
  out.push(`export type SupersurkhetSchemaIds = keyof ${rootTypeName};`);
  out.push(
    `export type SupersurkhetSchemaRow<TSchemaId extends SupersurkhetSchemaIds> = ${rootTypeName}[TSchemaId];`,
  );

  return out.join('\n');
}

async function loadConfig(configPath) {
  const abs = resolve(process.cwd(), configPath);
  if (!existsSync(abs)) {
    throw new Error(`Config file not found: ${configPath}`);
  }

  const imported = await import(pathToFileURL(abs).href);
  const config = imported.default ?? imported;
  if (!config || typeof config !== 'object') {
    throw new Error('Config must export an object');
  }
  return config;
}

function updateGitignore(projectDir) {
  const gitignorePath = join(projectDir, '.gitignore');
  const existing = existsSync(gitignorePath)
    ? readFileSync(gitignorePath, 'utf8')
    : '';
  if (existing.includes('.env.local')) return;
  const next = `${existing.trimEnd()}\n.env.local\n`;
  writeText(gitignorePath, next.startsWith('\n') ? next.slice(1) : next);
}

function cmdNew() {
  const name = args[1];
  if (!name) {
    throw new Error('Usage: supersurkhet new <project-name>');
  }

  const target = resolve(process.cwd(), name);
  ensureDir(target);
  ensureDir(join(target, 'supersurkhet'));

  writeText(
    join(target, '.env.local'),
    [
      '# Filled by future auth flow (blocked dependency).',
      'SUPERSURKHET_PROJECT_ID=',
      'SUPERSURKHET_API_KEY=',
      '',
    ].join('\n'),
  );

  updateGitignore(target);

  writeText(
    join(target, 'supersurkhet.config.mjs'),
    [
      '/** @type {{ projectId: string, schemaDocs: any[] }} */',
      'const config = {',
      "  projectId: 'local-dev',",
      '  schemaDocs: [',
      '    {',
      "      schemaId: 'product',",
      '      fields: [',
      "        { key: 'name', type: 'string', dataType: 'string', fieldType: 'string' },",
      "        { key: 'price', type: 'number', dataType: 'number', fieldType: 'currency' },",
      '      ],',
      '    },',
      '  ],',
      '};',
      '',
      'export default config;',
      '',
    ].join('\n'),
  );

  writeText(
    join(target, 'README.supersurkhet.md'),
    [
      '# Supersurkhet project',
      '',
      '1. Edit `supersurkhet.config.mjs` schema docs.',
      '2. Generate types:',
      `   node ./node_modules/supersurkhet-cli/bin/supersurkhet.mjs types --config supersurkhet.config.mjs --out supersurkhet/schema.types.ts`,
      '3. Push schema snapshot:',
      `   node ./node_modules/supersurkhet-cli/bin/supersurkhet.mjs sync-up --config supersurkhet.config.mjs`,
      '4. Pull schema snapshot:',
      `   node ./node_modules/supersurkhet-cli/bin/supersurkhet.mjs sync-down --config supersurkhet.config.mjs`,
      '',
    ].join('\n'),
  );

  console.log(`Created Supersurkhet project scaffold at ${target}`);
}

async function cmdTypes() {
  const configPath = parseFlag('--config', 'supersurkhet.config.mjs');
  const outPath = parseFlag('--out', 'supersurkhet/schema.types.ts');
  const rootTypeName = parseFlag('--root-type', 'SupersurkhetSchemaMap');

  const config = await loadConfig(configPath);
  const schemaDocs = Array.isArray(config.schemaDocs) ? config.schemaDocs : [];
  const output = generateTypes(schemaDocs, rootTypeName);

  writeText(resolve(process.cwd(), outPath), output);
  console.log(`Generated types at ${outPath}`);
}

async function cmdSyncUp() {
  const configPath = parseFlag('--config', 'supersurkhet.config.mjs');
  const relayStorePath = parseFlag('--store', '.supersurkhet/relay-store.json');

  const config = await loadConfig(configPath);
  const projectId = config.projectId ?? 'local-dev';
  const schemaDocs = Array.isArray(config.schemaDocs) ? config.schemaDocs : [];

  const relayAbs = resolve(process.cwd(), relayStorePath);
  const relayDoc = existsSync(relayAbs)
    ? JSON.parse(readFileSync(relayAbs, 'utf8'))
    : { projects: {} };

  relayDoc.projects[projectId] = {
    projectId,
    updatedAt: new Date().toISOString(),
    schemaDocs,
  };

  writeText(relayAbs, `${JSON.stringify(relayDoc, null, 2)}\n`);
  console.log(`Synced up ${schemaDocs.length} schema docs for project ${projectId}`);
}

async function cmdSyncDown() {
  const configPath = parseFlag('--config', 'supersurkhet.config.mjs');
  const relayStorePath = parseFlag('--store', '.supersurkhet/relay-store.json');
  const outPath = parseFlag('--out', 'supersurkhet/schema.synced.json');

  const config = await loadConfig(configPath);
  const projectId = config.projectId ?? 'local-dev';
  const relayAbs = resolve(process.cwd(), relayStorePath);

  if (!existsSync(relayAbs)) {
    throw new Error(`Relay store does not exist: ${relayStorePath}`);
  }

  const relayDoc = JSON.parse(readFileSync(relayAbs, 'utf8'));
  const project = relayDoc?.projects?.[projectId];
  if (!project) {
    throw new Error(`Project ${projectId} not found in relay store`);
  }

  writeText(resolve(process.cwd(), outPath), `${JSON.stringify(project, null, 2)}\n`);
  console.log(`Synced down project ${projectId} to ${outPath}`);
}

async function main() {
  try {
    if (!command || command === '--help' || command === 'help') {
      console.log('Supersurkhet CLI');
      console.log('  supersurkhet new <project-name>');
      console.log('  supersurkhet types --config supersurkhet.config.mjs --out supersurkhet/schema.types.ts');
      console.log('  supersurkhet sync-up --config supersurkhet.config.mjs [--store .supersurkhet/relay-store.json]');
      console.log('  supersurkhet sync-down --config supersurkhet.config.mjs [--store .supersurkhet/relay-store.json] [--out supersurkhet/schema.synced.json]');
      return;
    }

    if (command === 'new') return cmdNew();
    if (command === 'types') return await cmdTypes();
    if (command === 'sync-up') return await cmdSyncUp();
    if (command === 'sync-down') return await cmdSyncDown();

    throw new Error(`Unknown command: ${command}`);
  } catch (error) {
    console.error(error instanceof Error ? error.message : error);
    process.exit(1);
  }
}

await main();
